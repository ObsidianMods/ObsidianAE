    private static int slice(int attrId) {
        int lo = 0, hi = ATTRS.length - 1;
        while (lo <= hi) {
            int mid = (lo + hi) >>> 1;
            int v = ATTRS[mid];
            if (v == attrId) return mid;
            if (v < attrId) lo = mid + 1;
            else hi = mid - 1;
        }
        return -1;
    }

    /**
     * Symbol for an exact value match, or null. Aliased values resolve
     * to the last (modern) name, e.g. {@code match_parent} over
     * {@code fill_parent}.
     */
    public static String symbol(int attrId, int value) {
        int i = slice(attrId);
        if (i < 0) return null;
        String found = null;
        for (int j = OFFSETS[i]; j < OFFSETS[i + 1]; j++) {
            if (VALUES[j] == value) found = SYMBOLS[j];
        }
        return found;
    }

    /** Value for a symbol, or null. First match wins. */
    public static Integer value(int attrId, String symbol) {
        int i = slice(attrId);
        if (i < 0) return null;
        for (int j = OFFSETS[i]; j < OFFSETS[i + 1]; j++) {
            if (SYMBOLS[j].equals(symbol)) return VALUES[j];
        }
        return null;
    }
