    /** Qualified name ({@code android:type/name}) or null. */
    public static String get(int resId) {
        int lo = 0, hi = IDS.length - 1;
        while (lo <= hi) {
            int mid = (lo + hi) >>> 1;
            int v = IDS[mid];
            if (v == resId) return NAMES[mid];
            if (v < resId) lo = mid + 1;
            else hi = mid - 1;
        }
        return null;
    }

